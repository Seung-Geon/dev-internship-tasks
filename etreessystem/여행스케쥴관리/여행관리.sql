DROP TABLE CLIENT_INFO;

CREATE TABLE CLIENT_INFO (
	SEQ	VARCHAR(255)		NOT NULL,
	USER_NAME	VARCHAR(255)		NULL,
	USER_PHONE	VARCHAR(255)		NULL,
	TRAVE_CITY	VARCHAR(255)		NULL,
	PERIOD	VARCHAR(255)		NULL,
	EXPEND	VARCHAR(255)		NULL,
	TRANSPORT	VARCHAR(255)		NULL
);

DROP TABLE TRAVE_INFO;

CREATE TABLE TRAVE_INFO (
	TRAVE_SEQ	VARCHAR(255)		NOT NULL,
	SEQ	VARCHAR(255)		NOT NULL,
	TRAVE_DAY	VARCHAR(255)		NULL,
	TRAVE_TIME	VARCHAR(255)		NULL,
	TRAVE_CITY	VARCHAR(255)		NULL,
	TRAVE_COUNTY	VARCHAR(255)		NULL,
	TRAVE_LOC	VARCHAR(255)		NULL,
	TRAVE_TRANS	VARCHAR(255)		NULL,
	TRANS_TIME	VARCHAR(255)		NULL,
	USE_TIME	VARCHAR(255)		NULL,
	USE_EXPEND	VARCHAR(255)		NULL,
	TRAVE_DETAIL	VARCHAR(255)		NULL,
	REQUEST	VARCHAR(255)		NULL
);

ALTER TABLE CLIENT_INFO ADD CONSTRAINT PK_CLIENT_INFO PRIMARY KEY (
	SEQ
);

ALTER TABLE TRAVE_INFO ADD CONSTRAINT PK_TRAVE_INFO PRIMARY KEY (
	TRAVE_SEQ
